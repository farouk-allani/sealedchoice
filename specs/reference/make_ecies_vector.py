#!/usr/bin/env python3
"""
Generates specs/test-vectors/ecies-decrypt.json ONCE (ECIES encryption is
randomized, so this file is not regenerated by reference.py).

Library: eciespy 0.4.7 (same author and wire format as eciesjs and the Rust
`ecies` crate). Default config, which every implementation MUST use:
  curve secp256k1, ephemeral public key UNCOMPRESSED (65 bytes),
  HKDF-SHA256 over (ephemeral_pk_uncompressed || shared_point_uncompressed),
  AES-256-GCM with a 16-byte nonce, 16-byte tag.
  Wire format: ephemeral_pk(65) || nonce(16) || tag(16) || ciphertext.

Install (only needed to regenerate):  pip install eciespy==0.4.7
"""
import base64
import json
import sys
from pathlib import Path

import ecies
from ecies import PrivateKey

sys.path.insert(0, str(Path(__file__).parent))
import reference as r  # noqa: E402

keys = json.loads((r.VECTORS / "hashes-and-keys.json").read_text())
sk = bytes.fromhex(keys["tender_key"]["sk_hex"])
pk = bytes.fromhex(keys["tender_key"]["pk_compressed_hex"])
assert PrivateKey("secp256k1", sk).public_key.to_bytes(compressed=True) == pk, \
    "pure-python pubkey derivation disagrees with coincurve"

cases = []
for name in ("bid-a.json", "bid-b.json", "bid-c-malicious.json"):
    plain = r.jcs(json.loads((r.SPECS / "examples/bids" / name).read_text()))
    ct = ecies.encrypt(pk, plain)
    assert ecies.decrypt(sk, ct) == plain
    cases.append({"bid_file": f"examples/bids/{name}",
                  "plaintext_jcs_sha256": r.h(plain),
                  "ciphertext_b64": base64.b64encode(ct).decode(),
                  "ciphertext_sha256": r.h(ct),
                  "ciphertext_len": len(ct)})

out = {
    "description": "Decrypt each ciphertext with tender_key.sk_hex from hashes-and-keys.json (FAKE key) "
                   "and check sha256(plaintext) == plaintext_jcs_sha256. Plaintext is the JCS bytes of the bid file. "
                   "Wire format: ephemeral_pk_uncompressed(65)||nonce(16)||tag(16)||ciphertext.",
    "library": "eciespy 0.4.7 default config",
    "tender_sk_hex": sk.hex(), "tender_pk_compressed_hex": pk.hex(),
    "cases": cases,
}
(r.VECTORS / "ecies-decrypt.json").write_text(json.dumps(out, indent=2) + "\n")
print("wrote specs/test-vectors/ecies-decrypt.json")
